create extension if not exists "pgcrypto";

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  account_type text not null check (account_type in ('student','teacher')),
  school text,
  contact text,
  created_at timestamptz default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  description text,
  price numeric(10,2) not null check (price >= 0),
  image_url text,
  stock integer not null default 0 check (stock >= 0),
  created_at timestamptz default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  total_amount numeric(10,2) not null check (total_amount >= 0),
  status text not null default 'To Ship',
  created_at timestamptz default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0)
);

create table if not exists public.wishlists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz default now(),
  unique(user_id, product_id)
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  review_text text,
  created_at timestamptz default now()
);

-- Create a profile automatically after registration.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, account_type, school, contact)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    coalesce(new.raw_user_meta_data->>'account_type', 'student'),
    new.raw_user_meta_data->>'school',
    new.raw_user_meta_data->>'contact'
  )
  on conflict (id) do update set
    full_name = excluded.full_name,
    account_type = excluded.account_type,
    school = excluded.school,
    contact = excluded.contact;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Row Level Security
alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.wishlists enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile"
on public.profiles for select
using (auth.uid() = id);

drop policy if exists "Public can view products" on public.products;
create policy "Public can view products"
on public.products for select
using (true);

drop policy if exists "Users can view own orders" on public.orders;
create policy "Users can view own orders"
on public.orders for select
using (auth.uid() = user_id);

drop policy if exists "Users can create own orders" on public.orders;
create policy "Users can create own orders"
on public.orders for insert
with check (auth.uid() = user_id);

drop policy if exists "Users can view items from own orders" on public.order_items;
create policy "Users can view items from own orders"
on public.order_items for select
using (
  exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
    and o.user_id = auth.uid()
  )
);

drop policy if exists "Users can create items for own orders" on public.order_items;
create policy "Users can create items for own orders"
on public.order_items for insert
with check (
  exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
    and o.user_id = auth.uid()
  )
);

drop policy if exists "Users can view own wishlist" on public.wishlists;
create policy "Users can view own wishlist"
on public.wishlists for select
using (auth.uid() = user_id);

drop policy if exists "Users can manage own wishlist" on public.wishlists;
create policy "Users can manage own wishlist"
on public.wishlists for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can read reviews" on public.reviews;
create policy "Users can read reviews"
on public.reviews for select
using (true);

drop policy if exists "Users can create own reviews" on public.reviews;
create policy "Users can create own reviews"
on public.reviews for insert
with check (auth.uid() = user_id);

